    const localizedText = new WeakMap();

    function text(key, lang = activeLanguage) {
        if (!Object.hasOwn(messages.uk, key)) return key;
        return messages[normalizeLang(lang)]?.[key] ?? messages.uk[key] ?? key;
    }

    function translate(source, lang = activeLanguage) {
        const key = Object.hasOwn(sourceKeys, source) ? sourceKeys[source] : null;
        return key ? text(key, lang) : source;
    }

    function localize(root, lang = activeLanguage) {
        if (!root || !root.querySelectorAll) return;
        const selector = '[data-i18n], [data-i18n-placeholder], [data-i18n-title], [data-i18n-aria-label]';
        const nodes = [...(root.matches?.(selector) ? [root] : []), ...root.querySelectorAll(selector)];
        for (const node of nodes) {
            const key = node.getAttribute('data-i18n');
            if (key && Object.hasOwn(messages.uk, key)) {
                const value = text(key, lang);
                const current = node.textContent;
                const previous = localizedText.get(node);
                // A renderer can repurpose a node. Its new content is not ours to overwrite.
                if (current === previous || Object.values(messages).some(dict => dict[key] === current)) {
                    if (current !== value) node.textContent = value;
                    localizedText.set(node, value);
                }
            }
            for (const attribute of ['placeholder', 'title', 'aria-label']) {
                const attrKey = node.getAttribute('data-i18n-' + attribute);
                if (attrKey && Object.hasOwn(messages.uk, attrKey)) {
                    const value = text(attrKey, lang);
                    if (node.getAttribute(attribute) !== value) node.setAttribute(attribute, value);
                }
            }
        }
    }

    function setLanguage(lang) {
        activeLanguage = normalizeLang(lang);
        localize(document);
        if (!observer && typeof MutationObserver !== 'undefined') {
            observer = new MutationObserver(records => {
                // Only explicitly keyed source elements: never infer language from user text.
                for (const record of records) {
                    if (record.target.nodeType === 1) localize(record.target);
                }
            });
            observer.observe(document.body, {childList: true, subtree: true});
        }
        return activeLanguage;
    }

